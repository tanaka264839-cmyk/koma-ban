// 作り物の表の「今」は 2026-11-27（金）10:00（日本）。日たちは 11/27(金)・11/30(月)・12/1(火)。
'use strict';
const assert = require('node:assert/strict');
const path = require('node:path');

globalThis.芯 = require(process.env.KOMA_SHIN ? path.resolve(process.env.KOMA_SHIN) : '../芯/芯.js');
const 仕組み = require(process.env.KOMA_SHIKUMI ? path.resolve(process.env.KOMA_SHIKUMI) : './仕組み.js');
const 作り物の表 = require('../確かめ/作り物の表.js');

const 並び = [];
function 確かめる(守る, 名前, 中身) { 並び.push({ 守る, 名前, 中身 }); }

const 日たち = ['2026-11-27', '2026-11-30', '2026-12-01'];
let 通し = 0;
const 頼み = (中身) => Object.assign({ 通し番号: ++通し }, 中身 || {});
const 場所 = (担当, 段, 日 = 0) => ({ 日, 担当, 段 });
const 動かす頼み = (番号, 見ていた, 行き先) => 頼み({ 番号, 見ていた, 行き先 });

// 開いた後の表と口を作る
function 開いた表() {
  const 表 = 作り物の表.作る();
  const 返事 = 仕組み.開く(表.口, 頼み());
  assert.equal(返事.結果, '読んだ');
  表.数え直す();
  return 表;
}
const 一覧の駒 = (表, 番号, 日の並び = 日たち) => 芯.一覧を読む(表.中.一覧, 2, 日の並び).駒たち.find((k) => k.番号 === 番号);

