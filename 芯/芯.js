/*
 * 予定の盤：芯（判断だけを置く所）
 *
 * 画面（ブラウザ）と Google Apps Script の両方が、この同じ1つを使う。
 * だから、画面が「置ける」と見た手を、Google Apps Script も同じ決まりで確かめ直せる。
 *
 * 言葉
 *   日   … 盤の日。3つ（今日を含む平日3日）。駒の中では 0・1・2 の番号で持ち、表には日付の字（yyyy-MM-dd）で書く。
 *   盤   … 日ごとに、担当（列）× 時刻（段）。9:00〜18:00 を30分ずつ 18段。段0＝9:00。
 *   駒   … 予定1つ。{ 番号, 予定, 日, 担当, 段（始まりの段）, 段数 }
 *   一覧 … 駒の正本（表の「一覧」のシート）。盤は一覧から描く。
 *   棋譜 … 動かした記録。待った（一手戻す）は、戻した手の番号を持つ1行。
 *
 * ここには、表・画面・時計に触る物を置かない（同じ入力なら、いつも同じ答え）。今日の日付も、外から受け取る。
 */
