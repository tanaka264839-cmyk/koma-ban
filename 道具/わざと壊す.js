function 流す(確かめ, 環境名, 場所) {
  const 環境 = Object.assign({}, process.env, { KOMA_QUIET: '1', [環境名]: 場所 });
  const 結果 = spawnSync(process.execPath, [確かめ], { env: 環境, encoding: 'utf8', timeout: 120000 });
  return 結果.status;
}

function main() {
  const 対象 = process.argv[2] ? [process.argv[2]] : Object.keys(壊し方);
  const 置き場 = fs.mkdtempSync(path.join(os.tmpdir(), 'koma-ban-kowasu-'));
  let 全部 = 0;
  let 気づいた = 0;
  const 見逃し = [];
  for (const 名 of 対象) {
    const 組 = 壊し方[名];
    const 元の字 = fs.readFileSync(組.元, 'utf8');
    // 壊す前は、どの確かめも通ること
    for (const 確かめ of 組.確かめ) {
      if (!fs.existsSync(確かめ)) continue;
      if (流す(確かめ, 組.環境, 組.元) !== 0) throw new Error('壊す前から落ちています：' + 確かめ);
    }
    組.並び.forEach(([説明, 前, 後], i) => {
      const 数 = 元の字.split(前).length - 1;
      if (数 !== 1) throw new Error(`壊し方「${説明}」の元の字が ${数} か所あります（1か所にしてください）`);
      const 壊した = path.join(置き場, `${名}_${i + 1}.js`);
      fs.writeFileSync(壊した, 元の字.replace(前, 後), 'utf8');
      全部 += 1;
      const 落ちた = 組.確かめ.filter((確かめ) => fs.existsSync(確かめ) && 流す(確かめ, 組.環境, 壊した) !== 0);
      if (落ちた.length) 気づいた += 1;
      else 見逃し.push(`${名}：${説明}`);
    });
  }
  fs.rmSync(置き場, { recursive: true, force: true });
  console.log(`わざと壊す：${全部}通りのうち ${気づいた}通りに気づいた`);
  for (const 文 of 見逃し) console.log('  見逃し：' + 文);
  process.exitCode = 見逃し.length ? 1 : 0;
}

main();
